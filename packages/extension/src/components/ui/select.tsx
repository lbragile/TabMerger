type SelectContentElement = React.ElementRef<typeof SelectPrimitive.Content>;

function assignRef(ref: React.ForwardedRef<SelectContentElement>, node: SelectContentElement | null) {
  if (typeof ref === 'function') ref(node);
  else if (ref) ref.current = node;
}

const SelectContent = React.forwardRef<
  SelectContentElement,
  React.ComponentPropsWithoutRef<typeof SelectPrimitive.Content>
>(({ className, children, position = 'popper', ...props }, ref) => {
  // Radix closes an open Select on every window `resize`. A Firefox popup fires `resize` with
  // an unchanged size after DOM changes (opening the list is one), so the list closed as soon
  // as it opened. The content node only exists while the list is open, so the guard is added
  // and removed with it. See `stopSameSizeResizes`.
  const contentRef = React.useCallback(
    (node: SelectContentElement | null) => {
      assignRef(ref, node);
      if (!node) return;
      const stop = stopSameSizeResizes(node.ownerDocument.defaultView ?? window);
      return () => {
        stop();
        assignRef(ref, null);
      };
    },
    [ref]
  );

  return (
    <SelectPrimitive.Portal>
      <SelectPrimitive.Content
        ref={contentRef}
        className={cn(
          'relative z-50 max-h-96 min-w-[8rem] overflow-hidden rounded-none border bg-popover text-popover-foreground shadow-md data-[state=open]:animate-in data-[state=closed]:animate-out data-[state=closed]:fade-out-0 data-[state=open]:fade-in-0 data-[state=closed]:zoom-out-95 data-[state=open]:zoom-in-95 data-[side=bottom]:slide-in-from-top-2 data-[side=left]:slide-in-from-right-2 data-[side=right]:slide-in-from-left-2 data-[side=top]:slide-in-from-bottom-2',
          position === 'popper' &&
            'data-[side=bottom]:translate-y-1 data-[side=left]:-translate-x-1 data-[side=right]:translate-x-1 data-[side=top]:-translate-y-1',
          className
        )}
        position={position}
        {...props}
      >
        <SelectScrollUpButton />
        <SelectPrimitive.Viewport
          className={cn(
            'p-1',
            position === 'popper' &&
              'h-(--radix-select-trigger-height) w-full min-w-(--radix-select-trigger-width)'
          )}
        >
          {children}
        </SelectPrimitive.Viewport>
        <SelectScrollDownButton />
      </SelectPrimitive.Content>
    </SelectPrimitive.Portal>
  );
});
SelectContent.displayName = SelectPrimitive.Content.displayName;


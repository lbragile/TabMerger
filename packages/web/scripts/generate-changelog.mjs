/**
 * Copies the repo-root CHANGELOG.md (owned by semantic-release) into a TypeScript module,
 * `generated/changelog.ts`, that `lib/changelog.ts` imports. The /changelog page then needs no
 * filesystem at runtime: the release notes are part of the server bundle, so they work on hosts
 * without a filesystem (edge/worker runtimes) as well as on Node.
 *
 * Runs from next.config.ts (so every `next dev` / `next build`, whoever invokes it), from
 * Vitest's global setup, and before `tsc` in the `type-check` script. The output is git-ignored.
 *
 * Fails loudly: a missing CHANGELOG.md throws (the CLI exits 1), and a missing generated module
 * fails the build at the import. It never writes an empty module that would quietly hide the
 * generated releases.
 *
 *   node scripts/generate-changelog.mjs
 *
 * Plain JavaScript with Node built-ins only, so next.config.ts, Vitest and the CLI can all load
 * it without a TypeScript step.
 */
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const WEB_ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')

/** The repo-root changelog: packages/web/scripts → repo root. */
export const CHANGELOG_SOURCE = path.resolve(WEB_ROOT, '..', '..', 'CHANGELOG.md')

/** The generated module (git-ignored). */
export const CHANGELOG_MODULE = path.resolve(WEB_ROOT, 'generated', 'changelog.ts')

/**
 * The generated module's source for a given changelog. `JSON.stringify` gives a valid TS string
 * literal for any input; `<` is escaped as well so the text can't close a tag if it ever ends up
 * inside inline HTML.
 */
export function renderChangelogModule(markdown) {
  const literal = JSON.stringify(markdown).replace(/</g, '\\u003c')
  return [
    '// Generated by scripts/generate-changelog.mjs from the repo-root CHANGELOG.md. Do not edit.',
    '',
    '/** The raw markdown semantic-release writes; parsed by lib/changelog.ts. */',
    `export const CHANGELOG_MARKDOWN: string = ${literal}`,
    '',
  ].join('\n')
}

/**
 * Writes the module from `source` to `out`, only when its content changed (so `next dev` doesn't
 * see a fresh file, and recompile, on every start). Answers whether it wrote.
 */
export function generateChangelogModule({ source = CHANGELOG_SOURCE, out = CHANGELOG_MODULE } = {}) {
  let markdown
  try {
    markdown = fs.readFileSync(source, 'utf8')
  } catch (err) {
    throw new Error(
      `generate-changelog: cannot read ${source} (${err && err.code ? err.code : err}). ` +
        'The /changelog page is built from it; semantic-release keeps it at the repo root.'
    )
  }
  const next = renderChangelogModule(markdown)
  let current = null
  try {
    current = fs.readFileSync(out, 'utf8')
  } catch {
    // Not generated yet.
  }
  if (current === next) return false
  fs.mkdirSync(path.dirname(out), { recursive: true })
  fs.writeFileSync(out, next)
  return true
}

const invokedDirectly = process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)
if (invokedDirectly) {
  try {
    generateChangelogModule()
  } catch (err) {
    console.error(err instanceof Error ? err.message : err)
    process.exit(1)
  }
}
